"""Structured models for the LLM agent: the recommendation schema, grounded evidence and execution trace.

The language model must return an LLMTriageRecommendation. Every evidence item is tied to a tool call
that actually happened and to the source records that call returned. The execution trace records only
observable actions (tool calls and results); it never holds private reasoning.
"""

import re
from enum import StrEnum
from typing import Any, Self

from pydantic import AwareDatetime, Field, field_validator, model_validator

from models.goal_models import DecisionName, FrozenModel
from models.schemas import AssetCriticality, Priority, Severity
from models.tool_models import ToolName, ToolStatus

# Error text in a trace must be safe to show: no local paths and no stack traces.
_UNSAFE_TEXT = re.compile(r"[A-Za-z]:\\|/Users/|/home/|Traceback|File \"")


class RuntimeMode(StrEnum):
    MOCK = "MOCK"  # scripted test model: validates orchestration only, not a real language model
    OLLAMA = "OLLAMA"  # a real local model through ChatOllama


class CallStatus(StrEnum):
    """Outcome of one model-requested tool call."""

    SUCCESS = "SUCCESS"
    NOT_FOUND = "NOT_FOUND"
    INVALID_INPUT = "INVALID_INPUT"
    AMBIGUOUS = "AMBIGUOUS"
    ERROR = "ERROR"
    UNKNOWN_TOOL = "UNKNOWN_TOOL"
    DUPLICATE_CALL = "DUPLICATE_CALL"


def _no_blanks(values: tuple[str, ...], what: str) -> tuple[str, ...]:
    if any(not value.strip() for value in values):
        raise ValueError(f"{what} must not contain blank values")
    return values


class AssertedFacts(FrozenModel):
    """Optional machine-checkable facts an evidence item asserts; each is verified against the tool result."""

    failed_login_count: int | None = Field(default=None, ge=0)
    successful_login_count: int | None = Field(default=None, ge=0)
    matched_count: int | None = Field(default=None, ge=0)
    asset_criticality: AssetCriticality | None = None
    severity: Severity | None = None
    confirmed_impact: bool | None = None
    automatic_disruptive_action_permitted: bool | None = None
    human_authorization_required: bool | None = None

    def stated(self) -> dict[str, Any]:
        return {name: value for name, value in self.model_dump().items() if value is not None}


class GroundedEvidenceItem(FrozenModel):
    claim: str = Field(min_length=1, description="One factual statement taken from the tool result.")
    tool_name: ToolName
    tool_call_id: str = Field(min_length=1, description="The tool_call_id of the call that returned this evidence.")
    source_record_ids: tuple[str, ...] = Field(default=(), description="IDs of the source records that support the claim.")
    is_absence_observation: bool = Field(
        default=False, description="True only for 'nothing was found' observations from a successful call.")
    asserted_facts: AssertedFacts = AssertedFacts()

    @field_validator("source_record_ids")
    @classmethod
    def _ids_not_blank(cls, value: tuple[str, ...]) -> tuple[str, ...]:
        return _no_blanks(value, "source_record_ids")

    @model_validator(mode="after")
    def _substantive_evidence_needs_sources(self) -> Self:
        if not self.is_absence_observation and not self.source_record_ids:
            raise ValueError("a substantive evidence item must cite at least one source record ID")
        return self


class CompactLLMTriageDecision(FrozenModel):
    """Compact judgment generated by the final local-LLM decision stage.

    Evidence provenance is intentionally excluded. Tool names, tool-call IDs,
    source-record IDs and grounded evidence come from actual tool execution
    and are attached deterministically by application code.
    """

    priority: Priority
    decision: DecisionName
    uncertainty: str = Field(min_length=1, max_length=500)
    likely_interpretation: str = Field(min_length=1, max_length=500)
    recommended_actions: tuple[str, ...] = Field(min_length=1, max_length=6)

    @field_validator("recommended_actions")
    @classmethod
    def _recommended_actions_not_blank(
        cls,
        value: tuple[str, ...],
    ) -> tuple[str, ...]:
        return _no_blanks(value, "recommended_actions")
        
class LLMTriageRecommendation(FrozenModel):
    """The only structure the language model may return as its final answer."""

    priority: Priority
    decision: DecisionName
    evidence: tuple[GroundedEvidenceItem, ...] = Field(min_length=1)
    uncertainty: str = Field(min_length=1)
    likely_interpretation: str = Field(min_length=1)
    recommended_actions: tuple[str, ...] = Field(min_length=1)
    audit_note: str = Field(min_length=1)
    tools_called: tuple[str, ...] = Field(min_length=1)
    source_record_ids: tuple[str, ...] = Field(min_length=1)
    scenario_id: str | None = None
    grounding_summary: str | None = None
    tool_call_count: int | None = Field(default=None, ge=0)
    limitations: tuple[str, ...] = ()
    runtime_mode: RuntimeMode | None = None
    model_name: str | None = None

    @field_validator("recommended_actions", "limitations")
    @classmethod
    def _text_items_not_blank(cls, value: tuple[str, ...]) -> tuple[str, ...]:
        return _no_blanks(value, "text list")

    @field_validator("tools_called")
    @classmethod
    def _tool_names_not_blank(cls, value: tuple[str, ...]) -> tuple[str, ...]:
        return _no_blanks(value, "tools_called")

    @field_validator("source_record_ids")
    @classmethod
    def _source_ids_not_blank(cls, value: tuple[str, ...]) -> tuple[str, ...]:
        return _no_blanks(value, "source_record_ids")


class ToolObservation(FrozenModel):
    """One tool result as the model saw it, kept for grounding checks. Never claims more than it returned."""

    tool_call_id: str = Field(min_length=1)
    tool_name: str = Field(min_length=1)
    status: CallStatus
    arguments: dict[str, Any] = {}
    source_record_ids: tuple[str, ...] = ()
    evidence: dict[str, Any] | None = None
    summary: str = ""
    warnings: tuple[str, ...] = ()
    limitations: tuple[str, ...] = ()
    is_relevant: bool = False  # the result concerns this scenario's own alert, asset, policy or account
    is_absence: bool = False  # a NOT_FOUND or an empty search: a valid "nothing found" observation

    @property
    def is_reliable(self) -> bool:
        """Only a successful call is reliable factual evidence."""
        return self.status is CallStatus.SUCCESS

    @property
    def counts_as_evidence(self) -> bool:
        return self.is_reliable and self.is_relevant


class LLMToolCallRecord(FrozenModel):
    tool_call_id: str = Field(min_length=1)
    tool_name: str = Field(min_length=1)
    arguments: dict[str, Any]
    iteration: int = Field(ge=0)
    status: CallStatus
    source_record_ids: tuple[str, ...] = ()
    evidence_count: int = Field(default=0, ge=0)


class LLMToolResultRecord(FrozenModel):
    """Compact view of a tool result for the trace (no raw evidence payload)."""

    tool_call_id: str = Field(min_length=1)
    tool_name: str = Field(min_length=1)
    status: CallStatus
    summary: str = ""
    source_record_ids: tuple[str, ...] = ()
    warnings: tuple[str, ...] = ()
    is_relevant: bool = False
    is_absence: bool = False


class GuardrailResult(FrozenModel):
    name: str = Field(min_length=1)
    passed: bool
    detail: str = ""


class LLMExecutionTrace(FrozenModel):
    run_id: str = Field(min_length=1)
    scenario_id: str = Field(min_length=1)
    runtime_mode: RuntimeMode
    model_name: str = Field(min_length=1)
    started_at: AwareDatetime
    completed_at: AwareDatetime
    iterations: int = Field(ge=0)
    tool_calls: tuple[LLMToolCallRecord, ...] = ()
    tool_results: tuple[LLMToolResultRecord, ...] = ()
    source_record_ids: tuple[str, ...] = ()
    final_output_valid: bool
    guardrail_results: tuple[GuardrailResult, ...] = ()
    errors: tuple[str, ...] = ()
    warnings: tuple[str, ...] = ()

    @field_validator("errors", "warnings")
    @classmethod
    def _messages_must_be_safe(cls, value: tuple[str, ...]) -> tuple[str, ...]:
        if any(_UNSAFE_TEXT.search(item) for item in value):
            raise ValueError("trace messages must not contain local paths or stack traces")
        return value

    @model_validator(mode="after")
    def _times_must_be_ordered(self) -> Self:
        if self.completed_at < self.started_at:
            raise ValueError("completed_at must not be before started_at")
        return self


def status_from_tool(status: ToolStatus) -> CallStatus:
    return CallStatus(status.value)
